"""提示词构造：把 dsh-pet 的绿幕配方适配到本项目的 8×9 精灵表契约。

来源：PC2005-cloud/dsh-pet (MIT) `prompts/桌面宠物 10 秒动作提示词.md` 的「通用前缀」。
我们不是照抄它 16:9 / 10 秒的设定，原因有二：
  1. 我们的契约是 **1536×1872 = 8列×9行，单帧 192×208**（约 12:13），
     不是 16:9。按它的比例画会占不满画幅 → 素材缩放后细节糊。
  2. 我们只要 **4~8 帧** 就能构成一个循环动作（程序按 8fps 播），
     10 秒视频纯属浪费时间和钱（视频按秒计费）。

所以这里的做法是：**保留它对「绿幕 / 居中 / 安全区 / 首尾帧一致」的核心约束**，
把比例、时长、帧数换成我们的。
"""

from __future__ import annotations

# 我们的精灵表行语义（来自 docs/素材规格-hatch-pet格式.md，与源码一致）
ROW_SEMANTICS = [
    (0, "idle", "待机呼吸", 6),
    (1, "running-right", "向右跑", 8),
    (2, "running-left", "向左跑", 8),
    (3, "waving", "挥手打招呼", 4),
    (4, "jumping", "开心跳跃", 5),
    (5, "failed", "摔倒失败", 8),
    (6, "waiting", "原地等待/思考", 6),
    (7, "running", "原地跑动/忙碌", 6),
    (8, "review", "说话/讲解", 6),
]

# 我们的画幅：单帧 192×208 → 约 12:13（比 16:9 更方）
# Agnes 支持的 aspect_ratio 取最接近的：1:1 最稳（4:3 也行，但人物容易偏小）
ASPECT_RATIO = "1:1"

# 视频时长：帧数 / fps。用 5 秒 @ 12fps = 60 帧，够抠出 4~8 张。
SECONDS = "5"
FPS = 12

# 每行的动作描述（中文，直接进 prompt）
ROW_PROMPTS: dict[int, str] = {
    0: (
        "待机呼吸：角色原地站立，身体随呼吸极轻微地上下起伏，"
        "尾巴轻轻左右摇摆，双眼偶尔眨一下。双脚不移动。"
    ),
    1: (
        "向右小跑：角色身体明显侧向右方，四肢交替迈步，尾巴甩动，"
        "整体保持匀速，姿态轻快。注意角色本身朝右，但画面构图必须保持居中，"
        "不能真的往画面右边跑出去。"
    ),
    2: (
        "向左小跑：角色身体明显侧向左方，四肢交替迈步，尾巴甩动，"
        "整体保持匀速，姿态轻快。注意角色本身朝左，但画面构图必须保持居中，"
        "不能真的往画面左边跑出去。"
    ),
    3: (
        "挥手打招呼：角色抬起一只手在肩膀上方左右挥动，另一只手自然垂放，"
        "身体微微前倾，表情开心。双脚不移动。"
    ),
    4: (
        "开心跳跃：角色原地向上跳起，双脚离地、双臂高举欢呼，"
        "落地时膝盖微曲缓冲。跳跃幅度不要太高，双脚落回原位。"
    ),
    5: (
        "摔倒失败：角色失去平衡向右歪倒，膝盖先跪地，随后身体侧躺，"
        "最后保持一个沮丧的趴姿不动。动作在原地完成，不位移。"
    ),
    6: (
        "原地等待思考：角色双脚站定，双手在身前轻轻交叠，"
        "头部微微左右转动像在思考，偶尔眨眼。整体几乎静止。"
    ),
    7: (
        "原地忙碌跑动：角色双脚在原地快速交替踏步（像跑步机上跑），"
        "双手在身体两侧交替前后摆动，但双脚绝不真的向前移动。"
    ),
    8: (
        "讲解说话：角色面对镜头，双手在身前比划讲解，"
        "嘴巴一张一合像在说话，头部随讲解轻微点动。身体重心保持在原位。"
    ),
}

# 绿幕 + 构图强制约束（提炼自 dsh-pet 通用前缀）
GREEN_CONSTRAINTS = """
【硬性约束，逐条必须满足】
1. 背景是纯粹的纯色绿幕 #00FF00，铺满整个画面。没有阴影、没有地面、没有渐变、
   没有边框、没有杂物、没有文字。背景必须是单一纯色块。
2. 角色全程保持在画面正中，脚底落点恒定在画面水平中央，不允许 X/Y 平移位移。
   （原地跑、转身、跳跃都算原地，脚不能真的走到别处。）
3. 角色头顶距离画幅顶边留出约 25% 画幅高度的绿色空间，
   脚底距离画幅底边留出约 15% 画幅高度的绿色空间，
   身体左右两侧距离画幅边缘各留出约 15% 画幅宽度。
   任何一帧、任何身体部位（耳朵、尾巴、手脚）都不得触碰或超出画幅边缘。
4. 角色在所有帧里的大小和位置完全一致，只允许内部动作变化。
5. 每一帧角色的外形、颜色、画风必须完全一致（同一只角色，不要漂移、不要变形）。
6. 视频最后一帧要与第一帧几乎相同（回到标准正面站姿）。
7. 摄像机固定不动：不推拉、不摇移、不变焦、不旋转。
""".strip()


def build_prompt(character_desc: str, row: int) -> str:
    """构造某一行的完整提示词。

    Args:
        character_desc: 角色设定（外观 + 性格 + 配色），由调用方提供。
        row: 0~8 的行号。
    """
    action = ROW_PROMPTS.get(row)
    if action is None:
        raise ValueError(f"未知行号: {row}")
    return (
        f"【角色设定】{character_desc}\n\n"
        f"【本条视频要表现的动作】{action}\n\n"
        f"{GREEN_CONSTRAINTS}\n\n"
        f"画幅比例 {ASPECT_RATIO}，正方形构图。"
    )


def build_image_prompt(character_desc: str) -> str:
    """生成"标准正面站姿"参考图（用作视频首帧）。

    这一步是整条流水线的地基：视频用 keyframe 模式锁定首帧，
    首帧就是绿幕上的标准站姿，模型就会保持角色外观一致。
    """
    return (
        f"{character_desc}\n\n"
        "生成单张【标准正面全身站立】立绘，作为后续动画的第一帧参考：\n"
        "- 角色正面朝向镜头，双脚并拢站直，双手自然垂放，身体完整可见\n"
        "- 全身在画面正中，大小适中，四周留出充足绿色空间\n"
        f"- 背景是纯粹的纯色绿幕 #00FF00，铺满整个画面，无阴影、无地面、无渐变、无边框、无杂物\n"
        "- 画幅 1:1 正方形\n"
        "- 干净的粗描边卡通 / 二次元 Q 版风格，边缘锐利，不要柔光、不要光晕"
    )


def describe_frames(row: int) -> str:
    """给流水线下游看的帧数说明（不参与 prompt）。"""
    for r, name, _desc, n in ROW_SEMANTICS:
        if r == row:
            return f"{name}({n}帧)"
    return f"row{row}"
